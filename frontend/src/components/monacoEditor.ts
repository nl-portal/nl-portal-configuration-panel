// Loaded lazily by CodeEditor, so Monaco is its own chunk and only loads on pages with an editor.
// Serve Monaco from the bundle. Without this, @monaco-editor/react loads it from the jsDelivr CDN
// at runtime, which fails where the panel can't reach the internet.
import { Editor, loader } from "@monaco-editor/react";
import * as monaco from "monaco-editor";
import EditorWorker from "monaco-editor/esm/vs/editor/editor.worker?worker";
import CssWorker from "monaco-editor/esm/vs/language/css/css.worker?worker";
import JsonWorker from "monaco-editor/esm/vs/language/json/json.worker?worker";

window.MonacoEnvironment = {
  getWorker(_workerId: string, label: string) {
    if (label === "json") return new JsonWorker();
    if (label === "css" || label === "scss" || label === "less")
      return new CssWorker();
    return new EditorWorker();
  },
};

loader.config({ monaco });

export default Editor;
